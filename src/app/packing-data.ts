type RawItem = string | [string, string];

const group = (id: string, icon: string, title: string, raw: RawItem[]): PackingGroup => ({
  id,
  icon,
  title,
  items: raw.map((r) => {
    const [label, note] = typeof r === 'string' ? [r, undefined] : r;
    return { id: `${id}::${label}`, label, ...(note ? { note } : {}) };
  }),
});

